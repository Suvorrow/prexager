//! # Prexager
//!
//! Prexager is a GPU-accelerated desktop application for the interactive,
//! multi-scale exploration of 3D genome architecture — from whole-nucleus
//! chromosome territories down to molecular structures.
//!
//! ## Installation
//!
//! This crate serves as the official namespace placeholder and metadata index
//! for the Prexager project on crates.io.
//!
//! Because Prexager relies on heavy native system dependencies (HDF5, WebKitGTK, wgpu),
//! it is not distributed as a source-only `cargo install` package.
//!
//! Please download the pre-compiled binaries for your operating system from
//! the [GitHub Releases page](https://github.com/Suvorrow/prexager/releases).
